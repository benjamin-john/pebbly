revoke all on function bc_owntracks(text, jsonb) from public;
do $$
declare r text;
begin
  for r in select unnest(array['anon', 'authenticated']) loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke all on function bc_owntracks(text, jsonb) from %I', r);
    end if;
  end loop;
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    execute 'grant execute on function bc_owntracks(text, jsonb) to service_role';
  end if;
end $$;

